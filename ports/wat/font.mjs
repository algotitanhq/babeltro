// Generates font.wat, the 5x7 font as a data segment, from the Go source
// (go/internal/canvas/text.go): run `node ports/wat/font.mjs` from the repo
// root. Each glyph is 8 bytes, the 7 rows (bit 4 = leftmost pixel) and a
// zero pad, so glyph i starts at 0x14000 + 8*i.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const go = readFileSync(join(here, '../../go/internal/canvas/text.go'), 'utf8');
const src = go.slice(go.indexOf('const fontSrc = `') + 17);
const glyphs = Array.from({ length: 95 }, () => [0, 0, 0, 0, 0, 0, 0, 0]);
for (const line of src.slice(0, src.indexOf('`')).split('\n')) {
  const f = line.trim().split(/\s+/);
  if (f.length !== 8) continue;
  const idx = (f[0] === 'SPACE' ? 32 : f[0].charCodeAt(0)) - 32;
  for (let r = 0; r < 7; r++) glyphs[idx][r] = parseInt(f[r + 1], 2);
}
const hex = (b) => '\\' + b.toString(16).padStart(2, '0');
const out = [
  ';; font: the 5x7 bitmap font, generated by font.mjs from Go\'s canvas/text.go',
  ';;',
  ';; 95 glyphs, ASCII 32..126, 8 bytes each: rows 0..6 top to bottom, bit 4',
  ';; the leftmost pixel, then a zero pad. A data segment is copied into',
  ';; memory at instantiation; it is the one table here that is shipped,',
  ';; not computed, because a font is data, not maths.',
  '(data (i32.const 0x14000)',
  ...glyphs.map((g, i) => `  "${g.map(hex).join('')}"  ;; ${i === 0 ? 'SPACE' : String.fromCharCode(32 + i)}`),
  ')',
  '',
];
writeFileSync(join(here, 'font.wat'), out.join('\n'));
